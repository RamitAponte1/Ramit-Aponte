# Descripción: Operaciones básicas con dos números distintos

# 1. Declarar variables con valores diferentes
num1 = 15
num2 = 4

# 2. Realizar las operaciones matemáticas
suma = num1 + num2
resta = num1 - num2
multiplicacion = num1 * num2
division = num1 / num2

# 3. Mostrar los resultados
print("Suma:", suma)
print("Resta:", resta)
print("Multiplicación:", multiplicacion)
print("División:", division)